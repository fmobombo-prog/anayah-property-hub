CREATE EXTENSION IF NOT EXISTS http WITH SCHEMA extensions;

CREATE TABLE public.factures (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  agence_id uuid NOT NULL REFERENCES public.agences(id) ON DELETE CASCADE,
  numero text NOT NULL,
  type text NOT NULL DEFAULT 'facture' CHECK (type IN ('facture','avoir')),
  avoir_de uuid REFERENCES public.factures(id),
  origine text NOT NULL DEFAULT 'libre' CHECK (origine IN ('loyer','vente','cotisation','libre')),
  origine_ref text,
  statut text NOT NULL DEFAULT 'emise' CHECK (statut IN ('emise','annulee')),
  date_facture date NOT NULL DEFAULT current_date,
  objet text,
  mode_reglement text,
  client_nom text NOT NULL,
  client_type text NOT NULL DEFAULT 'individual' CHECK (client_type IN ('business','individual','government','foreign')),
  client_niu text, client_rccm text, client_adresse text, client_tel text, client_email text,
  client_assujetti boolean NOT NULL DEFAULT false,
  lignes jsonb NOT NULL DEFAULT '[]'::jsonb,
  total_ht numeric NOT NULL DEFAULT 0,
  total_tva numeric NOT NULL DEFAULT 0,
  total_ttc numeric NOT NULL DEFAULT 0,
  sfec_statut text NOT NULL DEFAULT 'non_certifiee' CHECK (sfec_statut IN ('non_certifiee','en_attente','certifiee','rejetee')),
  sfec_environnement text, sfec_signature text, sfec_signature_courte text, sfec_qr_code text,
  sfec_date_certification timestamptz, sfec_erreur jsonb,
  sfec_tentatives integer NOT NULL DEFAULT 0, sfec_derniere_tentative timestamptz,
  cree_par uuid DEFAULT auth.uid(),
  cree_le timestamptz NOT NULL DEFAULT now(),
  UNIQUE (agence_id, numero)
);
CREATE INDEX factures_agence_idx ON public.factures (agence_id, date_facture DESC);
GRANT SELECT ON public.factures TO authenticated;
GRANT ALL ON public.factures TO service_role;
ALTER TABLE public.factures ENABLE ROW LEVEL SECURITY;
CREATE POLICY factures_lecture ON public.factures FOR SELECT TO authenticated USING (role_dans(agence_id) IS NOT NULL OR est_super_admin());

CREATE TABLE public.factures_compteurs (
  agence_id uuid NOT NULL REFERENCES public.agences(id) ON DELETE CASCADE,
  prefixe text NOT NULL, annee int NOT NULL, dernier int NOT NULL DEFAULT 0,
  PRIMARY KEY (agence_id, prefixe, annee)
);
GRANT ALL ON public.factures_compteurs TO service_role;
ALTER TABLE public.factures_compteurs ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.sfec_config (
  agence_id uuid PRIMARY KEY REFERENCES public.agences(id) ON DELETE CASCADE,
  environnement text NOT NULL DEFAULT 'simulation' CHECK (environnement IN ('simulation','sandbox','production')),
  actif boolean NOT NULL DEFAULT true,
  cle_secret_id uuid, cle_fin text,
  maj_le timestamptz NOT NULL DEFAULT now(), maj_par uuid
);
GRANT SELECT ON public.sfec_config TO authenticated;
GRANT ALL ON public.sfec_config TO service_role;
ALTER TABLE public.sfec_config ENABLE ROW LEVEL SECURITY;
CREATE POLICY sfec_config_lecture ON public.sfec_config FOR SELECT TO authenticated USING (role_dans(agence_id) IS NOT NULL);

CREATE TABLE public.sfec_journal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agence_id uuid REFERENCES public.agences(id) ON DELETE CASCADE,
  facture_id uuid REFERENCES public.factures(id) ON DELETE SET NULL,
  environnement text, methode text, url text, requete jsonb, statut_http int, reponse jsonb,
  auteur_id uuid DEFAULT auth.uid(), cree_le timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sfec_journal_facture_idx ON public.sfec_journal (facture_id);
GRANT SELECT ON public.sfec_journal TO authenticated;
GRANT ALL ON public.sfec_journal TO service_role;
ALTER TABLE public.sfec_journal ENABLE ROW LEVEL SECURITY;
CREATE POLICY sfec_journal_lecture ON public.sfec_journal FOR SELECT TO authenticated USING (role_dans(agence_id) IN ('admin','gestionnaire'));

CREATE OR REPLACE FUNCTION public.facture_numero(a uuid, pre text, d date) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE n int; y int := extract(year from d);
BEGIN
  INSERT INTO factures_compteurs (agence_id, prefixe, annee, dernier) VALUES (a, pre, y, 1)
  ON CONFLICT (agence_id, prefixe, annee) DO UPDATE SET dernier = factures_compteurs.dernier + 1
  RETURNING dernier INTO n;
  RETURN pre || '-' || y || '-' || lpad(n::text, 5, '0');
END $$;
REVOKE ALL ON FUNCTION public.facture_numero(uuid,text,date) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.emettre_facture(a uuid, p jsonb) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE l jsonb; lignes jsonb := '[]'; ht numeric := 0; tva numeric := 0; q numeric; pu numeric; t numeric; lht numeric; ltva numeric;
  c jsonb := coalesce(p->'client', '{}'); ct text := coalesce(nullif(c->>'type',''), 'individual'); d date := coalesce(nullif(p->>'date','')::date, current_date);
  o text := coalesce(nullif(p->>'origine',''), 'libre'); ref text := nullif(p->>'origine_ref',''); nid uuid;
BEGIN
  IF NOT peut_ecrire(a) THEN RAISE EXCEPTION 'Votre rôle ou votre abonnement ne permet pas d''émettre de facture.' USING errcode = 'P0001'; END IF;
  IF coalesce(trim(c->>'nom'),'') = '' THEN RAISE EXCEPTION 'Indiquez le nom du client.' USING errcode = 'P0001'; END IF;
  IF ct NOT IN ('business','individual','government','foreign') THEN RAISE EXCEPTION 'Type de client inconnu.' USING errcode = 'P0001'; END IF;
  IF o NOT IN ('loyer','vente','cotisation','libre') THEN RAISE EXCEPTION 'Origine inconnue.' USING errcode = 'P0001'; END IF;
  IF ref IS NOT NULL AND EXISTS (SELECT 1 FROM factures WHERE agence_id = a AND origine = o AND origine_ref = ref AND type = 'facture' AND statut = 'emise') THEN
    RAISE EXCEPTION 'Cet encaissement a déjà une facture. Faites un avoir pour l''annuler avant de refacturer.' USING errcode = 'P0001'; END IF;
  IF jsonb_typeof(p->'lignes') <> 'array' OR jsonb_array_length(p->'lignes') = 0 THEN RAISE EXCEPTION 'La facture doit comporter au moins une ligne.' USING errcode = 'P0001'; END IF;
  FOR l IN SELECT * FROM jsonb_array_elements(p->'lignes') LOOP
    q := coalesce((l->>'quantite')::numeric, 1); pu := round(coalesce((l->>'prix_unitaire')::numeric, 0)); t := coalesce((l->>'taux_tva')::numeric, 0);
    IF coalesce(trim(l->>'designation'),'') = '' THEN RAISE EXCEPTION 'Chaque ligne doit avoir une désignation.' USING errcode = 'P0001'; END IF;
    IF q <= 0 OR pu < 0 THEN RAISE EXCEPTION 'Quantité ou prix invalide.' USING errcode = 'P0001'; END IF;
    IF t NOT IN (0,5,18) THEN RAISE EXCEPTION 'Taux de TVA non reconnu (0, 5 ou 18 %%).' USING errcode = 'P0001'; END IF;
    lht := round(q*pu); ltva := round(q*pu*t/100); ht := ht + lht; tva := tva + ltva;
    lignes := lignes || jsonb_build_object('designation', trim(l->>'designation'), 'type', CASE WHEN l->>'type' = 'product' THEN 'product' ELSE 'service' END,
      'quantite', q, 'prix_unitaire', pu, 'taux_tva', t, 'total_ht', lht, 'tva', ltva, 'total_ttc', lht + ltva);
  END LOOP;
  INSERT INTO factures (agence_id, numero, origine, origine_ref, date_facture, objet, mode_reglement, client_nom, client_type, client_niu, client_rccm,
    client_adresse, client_tel, client_email, client_assujetti, lignes, total_ht, total_tva, total_ttc)
  VALUES (a, facture_numero(a, 'FA', d), o, ref, d, nullif(trim(p->>'objet'),''), nullif(trim(p->>'mode_reglement'),''), trim(c->>'nom'), ct,
    nullif(regexp_replace(coalesce(c->>'niu',''), '\s', '', 'g'),''), nullif(trim(c->>'rccm'),''), nullif(trim(c->>'adresse'),''), nullif(trim(c->>'tel'),''),
    nullif(trim(c->>'email'),''), coalesce((c->>'assujetti')::boolean, false), lignes, ht, tva, ht + tva)
  RETURNING id INTO nid;
  RETURN nid;
END $$;

CREATE OR REPLACE FUNCTION public.emettre_avoir(f uuid, p_motif text) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE o factures; nid uuid;
BEGIN
  SELECT * INTO o FROM factures WHERE id = f FOR UPDATE;
  IF o.id IS NULL THEN RAISE EXCEPTION 'Facture introuvable.' USING errcode = 'P0001'; END IF;
  IF NOT peut_ecrire(o.agence_id) THEN RAISE EXCEPTION 'Votre rôle ou votre abonnement ne permet pas d''émettre d''avoir.' USING errcode = 'P0001'; END IF;
  IF o.type <> 'facture' OR o.statut <> 'emise' THEN RAISE EXCEPTION 'Cette facture est déjà annulée par un avoir.' USING errcode = 'P0001'; END IF;
  INSERT INTO factures (agence_id, numero, type, avoir_de, origine, origine_ref, date_facture, objet, mode_reglement, client_nom, client_type, client_niu,
    client_rccm, client_adresse, client_tel, client_email, client_assujetti, lignes, total_ht, total_tva, total_ttc)
  SELECT agence_id, facture_numero(agence_id, 'AV', current_date), 'avoir', id, origine, origine_ref, current_date,
    coalesce(nullif(trim(p_motif),''), 'Annulation de la facture ' || numero), mode_reglement, client_nom, client_type, client_niu,
    client_rccm, client_adresse, client_tel, client_email, client_assujetti, lignes, total_ht, total_tva, total_ttc
  FROM factures WHERE id = f RETURNING id INTO nid;
  UPDATE factures SET statut = 'annulee' WHERE id = f;
  RETURN nid;
END $$;

CREATE OR REPLACE FUNCTION public.sfec_regler(a uuid, p_env text, p_cle text, p_actif boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE c sfec_config; sid uuid; k text := nullif(trim(coalesce(p_cle,'')),'');
BEGIN
  IF role_dans(a) IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'Réservé aux administrateurs de l''agence.' USING errcode = 'P0001'; END IF;
  IF p_env NOT IN ('simulation','sandbox','production') THEN RAISE EXCEPTION 'Environnement inconnu.' USING errcode = 'P0001'; END IF;
  IF k IS NOT NULL AND length(k) < 16 THEN RAISE EXCEPTION 'Clé d''accès SFEC invalide (trop courte).' USING errcode = 'P0001'; END IF;
  SELECT * INTO c FROM sfec_config WHERE agence_id = a;
  sid := c.cle_secret_id;
  IF k IS NOT NULL THEN
    IF sid IS NOT NULL THEN PERFORM vault.update_secret(sid, k);
    ELSE sid := vault.create_secret(k, 'sfec_cle_' || a::text, 'Clé SFEC — agence ' || a::text); END IF;
  END IF;
  IF p_env <> 'simulation' AND sid IS NULL THEN RAISE EXCEPTION 'Saisissez la clé d''accès fournie par la DGID.' USING errcode = 'P0001'; END IF;
  INSERT INTO sfec_config (agence_id, environnement, actif, cle_secret_id, cle_fin, maj_le, maj_par)
    VALUES (a, p_env, coalesce(p_actif, true), sid, CASE WHEN k IS NOT NULL THEN right(k, 4) ELSE c.cle_fin END, now(), auth.uid())
  ON CONFLICT (agence_id) DO UPDATE SET environnement = excluded.environnement, actif = excluded.actif, cle_secret_id = excluded.cle_secret_id,
    cle_fin = excluded.cle_fin, maj_le = now(), maj_par = auth.uid();
END $$;

CREATE OR REPLACE FUNCTION public.sfec_payload(f uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE x factures; o factures; items jsonb; t18 numeric; t5 numeric; exo numeric; pm text;
BEGIN
  SELECT * INTO x FROM factures WHERE id = f;
  IF x.id IS NULL OR role_dans(x.agence_id) IS NULL THEN RAISE EXCEPTION 'Facture introuvable.' USING errcode = 'P0001'; END IF;
  IF x.avoir_de IS NOT NULL THEN SELECT * INTO o FROM factures WHERE id = x.avoir_de; END IF;
  SELECT coalesce(jsonb_agg(jsonb_build_object('designation', l->>'designation', 'type', l->>'type',
      'unit_price', (l->>'prix_unitaire')::numeric, 'quantity', (l->>'quantite')::numeric, 'discount_amount', 0,
      'subtotal', (l->>'total_ht')::numeric, 'amount_after_discount', (l->>'total_ht')::numeric,
      'tax_rate', trim(to_char((l->>'taux_tva')::numeric, 'FM990.##'), '.'), 'tax_amount', (l->>'tva')::numeric,
      'net_amount', (l->>'total_ttc')::numeric, 'total_amount', (l->>'total_ttc')::numeric)), '[]'),
    coalesce(sum((l->>'tva')::numeric) FILTER (WHERE (l->>'taux_tva')::numeric = 18), 0),
    coalesce(sum((l->>'tva')::numeric) FILTER (WHERE (l->>'taux_tva')::numeric = 5), 0),
    coalesce(sum((l->>'total_ht')::numeric) FILTER (WHERE (l->>'taux_tva')::numeric = 0), 0)
  INTO items, t18, t5, exo FROM jsonb_array_elements(x.lignes) l;
  pm := CASE WHEN x.mode_reglement ILIKE '%virement%' THEN 'bank_transfer' WHEN x.mode_reglement ILIKE '%esp%ce%' THEN 'cash'
    WHEN x.mode_reglement ILIKE '%ch%que%' THEN 'cheque' WHEN x.mode_reglement ILIKE '%mobile%' THEN 'mobile_money'
    WHEN x.mode_reglement ILIKE '%carte%' THEN 'card' WHEN x.mode_reglement ILIKE '%acompte%' OR x.mode_reglement ILIKE '%cr%dit%' THEN 'credit' ELSE NULL END;
  RETURN jsonb_strip_nulls(jsonb_build_object(
    'invoice_id', x.numero, 'invoice_type', CASE WHEN x.type = 'avoir' THEN 'creditNote' ELSE 'salesInvoice' END,
    'reference_invoice_id', o.numero, 'invoice_subject', x.objet,
    'recipient_type', x.client_type, 'recipient_name', x.client_nom, 'recipient_niu', x.client_niu, 'recipient_rccm', x.client_rccm,
    'recipient_address', x.client_adresse, 'recipient_phone', x.client_tel, 'recipient_email', x.client_email,
    'is_recipient_taxable', x.client_assujetti,
    'subtotal', x.total_ht, 'total_tax_t_amount', t18, 'total_tax_r_amount', t5, 'total_exempt_amount', exo,
    'total_tax_amount', x.total_tva, 'discount_amount', 0, 'total_line_discount_amount', 0, 'additional_cent_tax', 0,
    'electronic_stamp_duty', 0, 'total_amount', x.total_ttc, 'amount_due', x.total_ttc, 'currency', 'XAF',
    'payment_method', pm, 'items', items));
END $$;

CREATE OR REPLACE FUNCTION public.sfec_controler(f uuid) RETURNS text[]
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE x factures; o factures; e text[] := '{}';
BEGIN
  SELECT * INTO x FROM factures WHERE id = f;
  IF x.id IS NULL OR role_dans(x.agence_id) IS NULL THEN RAISE EXCEPTION 'Facture introuvable.' USING errcode = 'P0001'; END IF;
  IF x.sfec_statut = 'certifiee' THEN e := e || 'Facture déjà certifiée.'::text; END IF;
  IF x.type = 'facture' AND x.statut = 'annulee' AND NOT EXISTS (SELECT 1 FROM factures WHERE avoir_de = x.id AND sfec_statut <> 'certifiee') THEN NULL; END IF;
  IF x.client_type IN ('business','government','foreign') AND coalesce(x.client_nom,'') = '' THEN e := e || 'Nom du client obligatoire.'::text; END IF;
  IF x.client_type IN ('business','government') AND length(coalesce(x.client_niu,'')) NOT IN (16,17) THEN
    e := e || 'NIU du client obligatoire (16 ou 17 caractères) pour une entreprise ou une administration.'::text; END IF;
  IF x.client_type IN ('government','foreign') AND (x.client_adresse IS NULL OR x.client_tel IS NULL OR x.client_email IS NULL) THEN
    e := e || 'Adresse, téléphone et e-mail du client obligatoires pour une administration ou un client étranger.'::text; END IF;
  IF x.type = 'avoir' THEN
    SELECT * INTO o FROM factures WHERE id = x.avoir_de;
    IF o.sfec_statut IS DISTINCT FROM 'certifiee' THEN e := e || 'La facture d''origine doit d''abord être certifiée.'::text; END IF;
  END IF;
  RETURN e;
END $$;

CREATE OR REPLACE FUNCTION public.sfec_http(a uuid, _methode text, _chemin text, _corps jsonb, f uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions' AS $$
DECLARE c sfec_config; cle text; base text; r extensions.http_response; corps jsonb; st int;
BEGIN
  SELECT * INTO c FROM sfec_config WHERE agence_id = a;
  IF c.cle_secret_id IS NULL THEN RAISE EXCEPTION 'SFEC non configuré : enregistrez la clé d''accès de l''agence.' USING errcode = 'P0001'; END IF;
  SELECT decrypted_secret INTO cle FROM vault.decrypted_secrets WHERE id = c.cle_secret_id;
  base := CASE c.environnement WHEN 'production' THEN 'https://api.sfec.gouv.cg' ELSE 'https://sandbox.api.sfec.gouv.cg' END;
  PERFORM extensions.http_set_curlopt('CURLOPT_TIMEOUT_MS', '20000');
  BEGIN
    r := extensions.http((_methode, base || _chemin,
      ARRAY[extensions.http_header('X-API-Key', cle), extensions.http_header('Accept', 'application/json')],
      'application/json', CASE WHEN _corps IS NULL THEN NULL ELSE _corps::text END)::extensions.http_request);
    st := r.status;
    BEGIN corps := r.content::jsonb; EXCEPTION WHEN others THEN corps := jsonb_build_object('message', left(r.content, 2000)); END;
  EXCEPTION WHEN others THEN st := 0; corps := jsonb_build_object('message', 'Erreur réseau : ' || SQLERRM);
  END;
  INSERT INTO sfec_journal (agence_id, facture_id, environnement, methode, url, requete, statut_http, reponse)
    VALUES (a, f, c.environnement, _methode, base || _chemin, _corps, st, CASE WHEN corps ? 'qr_code' THEN (corps - 'qr_code') || '{"qr_code":"(image)"}' ELSE corps END);
  RETURN jsonb_build_object('status', st, 'body', corps, 'environnement', c.environnement);
END $$;
REVOKE ALL ON FUNCTION public.sfec_http(uuid,text,text,jsonb,uuid) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.sfec_certifier(f uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE x factures; c sfec_config; an text[]; res jsonb; st int; b jsonb; g jsonb; env text; sig text;
BEGIN
  SELECT * INTO x FROM factures WHERE id = f FOR UPDATE;
  IF x.id IS NULL OR NOT peut_ecrire(x.agence_id) THEN RAISE EXCEPTION 'Votre rôle ou votre abonnement ne permet pas de certifier.' USING errcode = 'P0001'; END IF;
  an := sfec_controler(f);
  IF array_length(an, 1) > 0 THEN RETURN jsonb_build_object('ok', false, 'statut', x.sfec_statut, 'anomalies', to_jsonb(an)); END IF;
  SELECT * INTO c FROM sfec_config WHERE agence_id = x.agence_id;
  env := coalesce(c.environnement, 'simulation');
  IF c.agence_id IS NOT NULL AND NOT c.actif THEN RAISE EXCEPTION 'La certification SFEC est désactivée pour cette agence.' USING errcode = 'P0001'; END IF;
  IF env = 'simulation' THEN
    sig := upper(substr(md5(x.id::text || clock_timestamp()::text), 1, 24));
    UPDATE factures SET sfec_statut = 'certifiee', sfec_environnement = 'simulation', sfec_signature = 'SIMULATION-' || sig,
      sfec_signature_courte = 'SIM-' || substr(sig, 1, 8), sfec_qr_code = NULL, sfec_date_certification = now(), sfec_erreur = NULL,
      sfec_tentatives = sfec_tentatives + 1, sfec_derniere_tentative = now() WHERE id = f;
    INSERT INTO sfec_journal (agence_id, facture_id, environnement, methode, url, requete, statut_http, reponse)
      VALUES (x.agence_id, f, 'simulation', 'POST', '(simulation)', sfec_payload(f), 201, jsonb_build_object('short_signature', 'SIM-' || substr(sig, 1, 8)));
    RETURN jsonb_build_object('ok', true, 'statut', 'certifiee', 'simulation', true, 'signature_courte', 'SIM-' || substr(sig, 1, 8));
  END IF;
  res := sfec_http(x.agence_id, 'POST', '/api/v1/invoices', sfec_payload(f), f);
  st := (res->>'status')::int; b := res->'body';
  IF st = 201 THEN
    UPDATE factures SET sfec_statut = 'certifiee', sfec_environnement = res->>'environnement', sfec_signature = b->>'signature',
      sfec_signature_courte = b->>'short_signature', sfec_qr_code = b->>'qr_code', sfec_date_certification = coalesce((b->>'certification_date')::timestamptz, now()),
      sfec_erreur = NULL, sfec_tentatives = sfec_tentatives + 1, sfec_derniere_tentative = now() WHERE id = f;
    RETURN jsonb_build_object('ok', true, 'statut', 'certifiee', 'signature_courte', b->>'short_signature');
  ELSIF st = 409 THEN
    g := sfec_http(x.agence_id, 'GET', '/api/v1/invoices/' || x.numero, NULL, f);
    IF (g->>'status')::int = 200 AND coalesce(g->'body'->>'certification_signature','') <> '' THEN
      UPDATE factures SET sfec_statut = 'certifiee', sfec_environnement = g->>'environnement', sfec_signature = g->'body'->>'certification_signature',
        sfec_signature_courte = g->'body'->>'certification_short_signature', sfec_qr_code = g->'body'->>'certification_qr_code',
        sfec_date_certification = coalesce((g->'body'->>'certification_date')::timestamptz, now()), sfec_erreur = NULL,
        sfec_tentatives = sfec_tentatives + 1, sfec_derniere_tentative = now() WHERE id = f;
      RETURN jsonb_build_object('ok', true, 'statut', 'certifiee', 'signature_courte', g->'body'->>'certification_short_signature');
    END IF;
  END IF;
  IF st IN (0, 429) OR st >= 500 THEN
    UPDATE factures SET sfec_statut = 'en_attente', sfec_erreur = b, sfec_tentatives = sfec_tentatives + 1, sfec_derniere_tentative = now() WHERE id = f;
    RETURN jsonb_build_object('ok', false, 'statut', 'en_attente', 'http', st, 'erreur', b);
  END IF;
  UPDATE factures SET sfec_statut = 'rejetee', sfec_erreur = b, sfec_tentatives = sfec_tentatives + 1, sfec_derniere_tentative = now() WHERE id = f;
  RETURN jsonb_build_object('ok', false, 'statut', 'rejetee', 'http', st, 'erreur', b);
END $$;

